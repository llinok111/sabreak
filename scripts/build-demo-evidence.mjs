/**
 * Produces the data the demo page reads, by running the real library in Node.
 *
 * The page itself only measures the browser (where Chromium actually starts new lines)
 * and intersects that with the positions recorded here. Keeping the library out of the
 * browser avoids having to ship a second bundle of a CommonJS transitive dependency,
 * and means every number on the page comes from the tested build rather than from a
 * re-implementation in the page.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import LineBreaker from '../dist/module.mjs';
import Upstream from 'linebreak';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'demo', 'evidence.mjs');

const SAMPLES = [
  { id: 'thai', label: 'Thai', font: 'Noto Sans Thai', text: 'การพัฒนาซอฟต์แวร์เป็นกระบวนการที่ต้องใช้ความพยายามอย่างต่อเนื่องและมีระเบียบวินัยในการทำงานร่วมกันเป็นทีม' },
  { id: 'lao', label: 'Lao', font: 'Noto Sans Lao', text: 'ການພັດທະນາຊອບແວເປັນຂະບວນການທີ່ຕ້ອງການຄວາມພະຍາຍາມຢ່າງຕໍ່ເນື່ອງ' },
  { id: 'khmer', label: 'Khmer', font: 'Noto Sans Khmer', text: 'ទ្រព្យរោងចក្រនិងបរិក្ខារត្រូវបានកំណត់តាមថ្លៃដើមប្រវត្តិដករំលស់បង្គរ' },
  { id: 'myanmar', label: 'Myanmar', font: 'Noto Sans Myanmar', text: 'ဆော့ဖ်ဝဲလ်ဖွံ့ဖြိုးတိုးတက်ရေးသည်စဉ်ဆက်မပြတ်အားထုတ်မှုလိုအပ်သောလုပ်ငန်းစဉ်တစ်ခုဖြစ်သည်' },
  { id: 'latin', label: 'Latin (control)', font: 'system sans', text: 'software development is a process that requires continuous discipline and teamwork' }
];

function segmentsOf (Breaker, text, options) {
  const b = new Breaker(text, options);
  const out = [];
  let last = 0;
  let bk;
  while ((bk = b.nextBreak())) {
    out.push({ position: bk.position, required: bk.required, text: text.slice(last, bk.position) });
    last = bk.position;
  }
  return out;
}

// No timestamp: the output must be a pure function of the build, otherwise the Pages
// freshness check and any byte-level packaging check would flag it as changed on every
// run for no reason.
const evidence = {
  node: process.version,
  icu: process.versions.icu,
  capabilities: LineBreaker.saCapabilities(),
  samples: SAMPLES.map((s) => {
    const dictPositions = [...LineBreaker.saBreakOpportunities(s.text)];
    const sabreak = segmentsOf(LineBreaker, s.text);
    const upstream = segmentsOf(Upstream, s.text);
    return {
      ...s,
      charCount: [...s.text].length,
      sabreakSegments: sabreak.map(r => ({ position: r.position, required: r.required, text: r.text })),
      upstreamSegments: upstream.map(r => ({ position: r.position, required: r.required, text: r.text })),
      dictionaryPositions: dictPositions
    };
  })
};

fs.writeFileSync(OUT, `// Generated by scripts/build-demo-evidence.mjs — do not edit.\nexport default ${JSON.stringify(evidence, null, 2)};\n`);
process.stdout.write(`demo/evidence.mjs  ${(fs.statSync(OUT).size / 1024).toFixed(1)} kB\n`);
for (const s of evidence.samples) {
  process.stdout.write(`  ${s.label.padEnd(16)} upstream=${String(s.upstreamSegments.length).padStart(2)} sabreak=${String(s.sabreakSegments.length).padStart(2)} (dictionary-derived ${s.dictionaryPositions.length})\n`);
}
